import Foundation
import Observation

// Port of `TelegramSession.kt`.

/// What the user sees of the Telegram connection.
public enum TelegramState: Sendable, Equatable {
    case starting
    /// Phone: enter the phone number.
    case needsPhoneNumber
    case needsCode
    case needsPassword(hint: String)
    /// TV: waiting for the household phone (or a QR scan) to approve `link`.
    case waitingForApproval(link: String)
    case ready(TgUser)
    case signedOut
    case failed(String)
}

/// What an approved login signed in; `session` is nil when Telegram hadn't listed it within ~12 s.
public struct ApprovedLogin: Sendable, Equatable {
    public var session: TgSessionInfo?
    public init(session: TgSessionInfo?) { self.session = session }
}

/// Where the session runs: the phone logs in with number and code, a TV through QR / phone approval.
public enum TelegramRole: Sendable { case phone, tv }

/// One device's Telegram session. Drives TDLib's authorization states, accepts one user input at a time (a second tap while a
/// request is in flight caused "Another authorization query has started" in the spike), and exposes the result as `state`.
@MainActor @Observable
public final class TelegramSession {
    /// The Telegram layer this session signs in with; the library sync and file reader use it too.
    @ObservationIgnored public nonisolated let api: any TelegramApi
    public private(set) var state: TelegramState = .starting
    /// True while a phone number, code or password is being checked.
    public private(set) var busy = false
    /// Why the last phone number, code or password was rejected; cleared when Telegram moves on.
    public private(set) var lastError: String?
    /// Identity actually used to start this session, also used to verify newly approved devices.
    @ObservationIgnored public private(set) var clientApiId = 0

    @ObservationIgnored private let role: TelegramRole
    @ObservationIgnored private let parameters: @Sendable () async throws -> TgParameters
    @ObservationIgnored private var startupUnavailable = false
    @ObservationIgnored private var startingUp = false
    @ObservationIgnored private var inputBusy = false
    @ObservationIgnored private var job: Task<Void, Never>?
    @ObservationIgnored private let identifyWait: Duration

    public init(api: any TelegramApi, role: TelegramRole, identifyWait: Duration = .seconds(2), parameters: @escaping @Sendable () async throws -> TgParameters) {
        self.api = api; self.role = role; self.parameters = parameters; self.identifyWait = identifyWait
    }

    /// Retry configuration without recreating TDLib or deleting an existing account database.
    public func retryStartup() {
        guard startupUnavailable, !startingUp else { return }
        startupUnavailable = false
        startingUp = true
        state = .starting
        Task { await handle(.waitParameters); startingUp = false }
    }

    public func start() {
        guard job == nil else { return }
        // Subscribe before the loop runs, so the first state cannot be missed.
        let states = api.authStates
        job = Task { [weak self] in
            for await auth in states { await self?.handle(auth) }
        }
    }

    public func stop() { job?.cancel(); job = nil }

    public func submitPhoneNumber(_ phone: String) { submit { try await self.api.setPhoneNumber(Self.normalizePhone(phone)) } }
    public func submitCode(_ code: String) { submit { try await self.api.checkCode(code.filter(\.isNumber)) } }
    public func submitPassword(_ password: String) { submit { try await self.api.checkPassword(password) } }

    public func logOut() { Task { try? await api.logOut() } }

    /// Phone only: sign a TV in to this account from its login link, as Telegram's "Scan QR" does.
    public func approveTvLogin(link: String, ownApiId: Int) async -> Result<ApprovedLogin, TgError> {
        precondition(role == .phone, "only the phone approves TV logins")
        return await approveVerified(link, ownApiId)
    }

    /// TV only: signs the household phone in to this account from the phone's login link, as the phone does for a TV.
    public func approvePhoneLogin(link: String, ownApiId: Int) async -> Result<ApprovedLogin, TgError> {
        precondition(role == .tv, "only a TV approves phone logins")
        return await approveVerified(link, ownApiId)
    }

    /// Approves a login link and checks what it signed in. A link carries no proof of which app made it, so a link generated by another
    /// Telegram client (e.g. Telegram Desktop on someone else's laptop) would get a full session on the owner's account. So:
    ///  - the sessions are listed first; if that fails, nothing is approved;
    ///  - the one new session must use Cablegram's API id (`ownApiId`); if the only new session is another app's, it is ended at once
    ///    and the approval fails (`UNEXPECTED_CLIENT`);
    ///  - the identified session is returned, so the phone can end exactly that one later, never an unrelated session such as the
    ///    owner's own desktop.
    private func approveVerified(_ link: String, _ ownApiId: Int) async -> Result<ApprovedLogin, TgError> {
        guard Self.isLoginLink(link) else { return .failure(TgError(code: 0, name: "NOT_A_LOGIN_LINK")) }
        let before: Set<Int64>
        do { before = Set(try await api.activeSessions().map(\.id)) } catch let error as TgError { return .failure(TgError(code: error.code, name: "SESSIONS_UNAVAILABLE")) } catch { return .failure(TgError(code: 0, name: "SESSIONS_UNAVAILABLE")) }
        do { try await api.confirmQrLogin(link) } catch let error as TgError { return .failure(error) } catch { return .failure(TgError(code: 0, name: "CONFIRM_FAILED")) }
        for attempt in 0..<Self.identifyAttempts {
            let fresh = ((try? await api.activeSessions()) ?? []).filter { !$0.isCurrent && !before.contains($0.id) }
            if let own = fresh.filter({ $0.apiId == ownApiId }).max(by: { $0.logInDate < $1.logInDate }) { return .success(ApprovedLogin(session: own)) }
            if fresh.count == 1 {
                try? await api.terminateSession(fresh[0].id)
                return .failure(TgError(code: 403, name: "UNEXPECTED_CLIENT"))
            }
            if attempt < Self.identifyAttempts - 1 { try? await Task.sleep(for: identifyWait) }
        }
        // Approved, but Telegram hasn't listed the new session yet: it can't be ended remotely.
        return .success(ApprovedLogin(session: nil))
    }

    /// Phone only: sign in with a QR login (approved by a Home TV) instead of a phone number and code.
    public func startQrLogin() {
        precondition(role == .phone, "a TV always starts with a QR login")
        submit { try await self.api.requestQrLogin() }
    }

    /// The household's library channel. Opened by id when the household link already has one (`knownChatId`); otherwise found by title,
    /// or created when `allowCreate` (phone only). Media sync reads only this channel; the optional bot picker separately reads public
    /// Bot Hubs posts.
    ///
    /// With `logoPath`, a channel Cablegram creates gets the Cablegram logo, and so does an existing one without a photo; a photo the
    /// owner chose is never replaced. A failed photo upload doesn't fail linking.
    public func openLibrary(knownChatId: Int64?, allowCreate: Bool, logoPath: String? = nil) async throws -> TgLibrary? {
        var existing: TgChat?
        if let knownChatId, let chat = await api.chat(knownChatId), chat.isMember { existing = chat }
        if existing == nil, let found = try await api.findChatByTitle(Self.libraryTitle), let chat = await api.chat(found), chat.isMember { existing = chat }
        let library: TgLibrary
        if let existing { library = TgLibrary(chatId: existing.id, created: false) }
        else if allowCreate { library = TgLibrary(chatId: try await api.createChannel(title: Self.libraryTitle, description: Self.libraryDescription), created: true) }
        else { return nil }
        if let logoPath, library.created || existing?.hasPhoto == false { try? await api.setChannelPhoto(chatId: library.chatId, imagePath: logoPath) }
        return library
    }

    /// False when the owner left the linked channel or it was deleted: its videos are out of reach.
    public func isLibraryAvailable(_ chatId: Int64) async -> Bool { await api.chat(chatId)?.isMember == true }

    func handle(_ auth: TgAuthState) async {
        lastError = nil
        do {
            switch auth {
            case .waitParameters:
                let supplied = try await parameters()
                clientApiId = supplied.apiId
                try await api.start(supplied)
            case .waitPhoneNumber:
                if role == .tv { state = .starting; try await api.requestQrLogin() } else { state = .needsPhoneNumber }
            case .waitCode: state = .needsCode
            case let .waitPassword(hint): state = .needsPassword(hint: hint)
            case let .waitOtherDevice(link): state = .waitingForApproval(link: link)
            case .ready: state = .ready(try await api.me())
            case .loggingOut, .closed: state = .signedOut
            case let .unsupported(name): state = .failed(Self.unsupportedMessage(name))
            }
        } catch is TelegramClientUnavailable {
            startupUnavailable = true
            state = .failed(TelegramClientUnavailable.message)
        } catch let error as TgError {
            state = .failed(Self.describe(error))
        } catch {
            state = .failed(TelegramClientUnavailable.message)
        }
    }

    private func submit(_ request: @escaping @MainActor () async throws -> Void) {
        guard !inputBusy else { return }
        inputBusy = true
        busy = true
        Task {
            do { try await request() } catch let error as TgError {
                // Stay on the same step so the user can correct it; the message says what went wrong.
                lastError = Self.describe(error)
            } catch {}
            busy = false
            inputBusy = false
        }
    }

    static let identifyAttempts = 6
    public static let libraryTitle = "Cablegram library"
    public static let libraryDescription = "Videos you share here appear in Cablegram on your TV."

    /// `tg://login?token=…`: what Telegram's "Scan QR" opens.
    public static func isLoginLink(_ link: String) -> Bool {
        link.range(of: #"^tg://login\?token=[A-Za-z0-9_=-]{16,512}$"#, options: .regularExpression) != nil
    }

    /// Keeps digits and a leading +; Telegram wants the number in international format.
    public static func normalizePhone(_ raw: String) -> String {
        let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        let digits = trimmed.filter(\.isNumber)
        guard trimmed.hasPrefix("+") || trimmed.hasPrefix("00") else { return digits }
        return "+" + (trimmed.hasPrefix("00") ? String(digits.dropFirst(2)) : digits)
    }

    public static func describe(_ error: TgError) -> String {
        if let wait = error.retryAfterSeconds { return "Telegram asks to wait \(formatWait(wait)) before trying again." }
        let name = error.name
        if name.contains("PHONE_NUMBER_INVALID") { return "That phone number isn't valid. Include the country code, e.g. +31." }
        if name.contains("PHONE_CODE_INVALID") { return "That code isn't right. Check the latest code in Telegram." }
        if name.contains("PHONE_CODE_EXPIRED") { return "That code expired. Request a new one." }
        if name.contains("PASSWORD_HASH_INVALID") { return "That password isn't right." }
        if name.contains("SESSION_TOO_FRESH") || name.contains("FRESH_RESET_AUTHORISATION_FORBIDDEN") {
            return "Telegram doesn't allow this from a session less than 24 hours old. Try again later."
        }
        // TDLib cannot open its local database (damaged, or its key was lost): only a fresh sign-in helps.
        if name.range(of: "database|malformed|encryption key|wrong key", options: [.regularExpression, .caseInsensitive]) != nil {
            return "Telegram's data on this device is damaged. Disconnect Telegram and connect it again."
        }
        return "Telegram error: \(name)"
    }

    private static func formatWait(_ seconds: Int) -> String {
        switch seconds {
        case ..<90: "\(seconds) seconds"
        case ..<5400: "\((seconds + 59) / 60) minutes"
        default: "\((seconds + 3599) / 3600) hours"
        }
    }

    private static func unsupportedMessage(_ name: String) -> String {
        switch name {
        case "WaitRegistration": "This phone number has no Telegram account. Create one in the Telegram app first."
        case "WaitEmailAddress", "WaitEmailCode": "Telegram asks for an email step. Finish signing in once in the Telegram app, then try again."
        case "WaitPremiumPurchase": "Telegram requires Premium to sign in on a new device from this number."
        default: "Telegram asked for a step Cablegram doesn't support (\(name))."
        }
    }
}
